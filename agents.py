import ollama

MODELE_CERVEAU = "satgeze/gemma4-12b-uncensored-1m:latest"
MODELE_RELECTEUR = "hf.co/mradermacher/DeepSeek-V4-Pro-Qwen3.5-9B-UNCENSORED-heretic-i1-GGUF:Q4_K_M"

# mêmes modèles pour l'agent
MODELE_PLANNER = MODELE_CERVEAU
MODELE_CODER = MODELE_CERVEAU
MODELE_REVIEWER = MODELE_RELECTEUR

SYSTEM_CERVEAU = """You are the project lead / brain of TrappistCode.
Analyze the request thoroughly, break it down into clear steps, and provide a complete and well-argued answer.
If code is needed, write it clearly.
You can decide to call tools or ask for a review when useful."""

SYSTEM_RELECTEUR = """You are a critical reviewer.
You are given a question and an answer generated by another model.

Your mission:
1. Check logical and factual consistency
2. Correct any errors or inaccuracies
3. Improve clarity and structure
4. Add clear comments in French
5. Provide a clean and improved final version

If the answer is already good, say so and do not invent problems."""

def cerveau(question: str, mode_construction: bool = False) -> str:
    print("→ Gemma réfléchit...")
    try:
        response = ollama.chat(
            model=MODELE_CERVEAU,
            messages=[
                {"role": "system", "content": SYSTEM_CERVEAU},
                {"role": "user", "content": question}
            ],
            options={"num_ctx": 4096, "num_predict": 1024}
        )
        reponse_gemma = response["message"]["content"]
    except Exception as e:
        return f"Erreur cerveau: {e}"

    if not mode_construction:
        print("→ Question simple → Gemma seul")
        return reponse_gemma

    print("→ Mode construction → appel DeepSeek")
    prompt = f"""Original question:
{question}

Answer from Gemma:
{reponse_gemma}

---
Review the answer, correct it if needed, and comment the code in French.
Provide a clean final version."""

    try:
        review = ollama.chat(
            model=MODELE_RELECTEUR,
            messages=[
                {"role": "system", "content": SYSTEM_RELECTEUR},
                {"role": "user", "content": prompt}
            ],
            options={"num_ctx": 4096, "num_predict": 1024}
        )
        return review["message"]["content"]
    except Exception as e:
        return f"Erreur relecteur: {e}\n\nRéponse Gemma:\n{reponse_gemma}"

if __name__ == "__main__":
    question = input("Question : ")
    mode = input("Mode construction ? (o/n) : ").strip().lower() == "o"

    print("\n" + "="*50)
    resultat = cerveau(question, mode_construction=mode)
    print("\n=== Réponse finale ===")
    print(resultat)